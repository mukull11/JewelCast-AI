"""Historical inventory simulation with no look-ahead.

At each simulated day
---------------------
1. Receive purchase orders whose expected arrival date is today.
2. On review dates, use a forecast whose origin is yesterday to decide whether
   to order. Only information available at the start of the day is used.
3. Serve that day's observed demand, lost sales become unmet units.
4. Update on-hand stock and continue.

Controlled comparison
---------------------
All policies start from the same on-hand stock at the simulation start date and
an empty pipeline by default, and face the same observed daily demand and the
same supplier lead times. Historical opening purchase orders are not inherited
because they were generated by the original simulation policy.

Demand caveat
-------------
The synthetic generator stores stockout-censored observed sales, not latent
customer demand. The simulation therefore treats observed ``units_sold`` as the
demand proxy. It does not claim to reconstruct true lost demand. Every policy
sees the same proxy, so the policy comparison is internally consistent while
absolute fill rates may be optimistic.
"""

