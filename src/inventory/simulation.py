@dataclass
class SimulationResult:
    policy: str
    daily: pd.DataFrame
    decisions: pd.DataFrame
    orders: pd.DataFrame
    metadata: dict[str, Any] = field(default_factory=dict)


def _opening_stock(
    panel: ForecastingPanel,
    start: pd.Timestamp,
    end: pd.Timestamp,
    skus: pd.Index,
) -> dict[str, float]:
    frame = panel.frame
    start_rows = frame.loc[frame["date"] == start].drop_duplicates(subset=["sku"], keep="last").set_index("sku")
    opening: dict[str, float] = {}
    for sku in skus:
        value = start_rows["available_stock"].get(sku, np.nan)
        if pd.isna(value):
            earlier = frame.loc[(frame["sku"].astype(str) == str(sku)) & (frame["date"] < start)]
            if not earlier.empty:
                value = earlier.sort_values("date").iloc[-1]["available_stock"]
        if pd.isna(value):
            continue
        opening[str(sku)] = max(0.0, float(value))
    return opening


def _simulation_skus(panel: ForecastingPanel, start: pd.Timestamp, end: pd.Timestamp) -> pd.Index:
    frame = panel.frame
    first_dates = frame.groupby("sku", observed=True)["date"].min()
    eligible = [
        str(sku)
        for sku, first in first_dates.items()
        if pd.Timestamp(first) <= start
        and frame.loc[(frame["sku"].astype(str) == str(sku)) & (frame["date"] <= end), "date"].max()
        >= start
    ]
    return pd.Index(sorted(eligible), name="sku")


def _forecast_lookup(forecast: pd.DataFrame | None, start: pd.Timestamp) -> dict[str, np.ndarray]:
    if forecast is None or forecast.empty:
        return {}
    view = forecast.copy()
    view["sku"] = view["sku"].astype(str)
    view["date"] = pd.to_datetime(view["date"]).dt.normalize()
    view = view.loc[view["date"] >= start].sort_values(["sku", "date"])
    lookup: dict[str, np.ndarray] = {}
    for sku, group in view.groupby("sku", observed=True):
        lookup[str(sku)] = pd.to_numeric(group["predicted_units"], errors="coerce").fillna(0.0).clip(lower=0.0).to_numpy(dtype=float)
    return lookup


def _history_lookup(daily: pd.DataFrame, origin: pd.Timestamp, window: int, skus: pd.Index) -> dict[str, np.ndarray]:
    frame = daily_demand_history(daily, origin, window, skus=skus)
    lookup: dict[str, np.ndarray] = {}
    for _, row in frame.iterrows():
        value = row["history"]
        lookup[str(row["sku"])] = np.asarray(value, dtype=float) if isinstance(value, np.ndarray) else np.array([], dtype=float)
    return lookup


def _category_map(panel: ForecastingPanel, skus: pd.Index) -> dict[str, str]:
    latest = panel.frame.drop_duplicates(subset=["sku"], keep="last").set_index("sku")["category"]
    return {str(sku): str(latest.get(sku, "Unknown")) for sku in skus}


def simulate_policy(
    panel: ForecastingPanel,
    data: InventoryData,
    config: Mapping[str, Any],
    policy: str,
    forecast_provider: ForecastProvider | None = None,
    start_date: Any | None = None,
    end_date: Any | None = None,
    decision_frequency_days: int | None = None,
    horizon: int | None = None,
    service_level: float | None = None,
    demand_multiplier: float = 1.0,
) -> SimulationResult:
    """Simulate one replenishment policy over the historical window."""
    if policy not in SUPPORTED_POLICIES:
        raise ValueError(f"Unsupported simulation policy: {policy}. Choose from {SUPPORTED_POLICIES}")
    settings = inventory_settings(config)
    sim = settings["simulation"]
    start = as_timestamp(start_date or sim["start_date"])
    end = as_timestamp(end_date or sim["end_date"])
    if end <= start:
        raise ValueError("simulation end_date must be after start_date")
    frequency = max(1, int(decision_frequency_days or sim["decision_frequency_days"]))
    forecast_horizon = int(horizon or sim["horizon"])
    level = float(service_level if service_level is not None else settings["service_level"])

    lead, _flags, _meta = _lead_series(data, settings)
    skus = _simulation_skus(panel, start, end)
    if len(skus) == 0:
        raise ValueError("No SKUs have inventory history at the simulation start date")
    opening = _opening_stock(panel, start, end, skus)
    skus = pd.Index(sorted(opening), name="sku")
    if len(skus) == 0:
        raise ValueError("No opening inventory available for the simulation window")

    if policy == "simple_rop":
        provider: ForecastProvider | None = TrailingMeanForecastProvider(
            panel,
            window_days=int(settings["demand_volatility_window_days"]),
            min_history=int(settings["min_history_days_for_volatility"]),
        )
    else:
        provider = forecast_provider
        if provider is None:
            raise ValueError("forecast_driven policy requires a forecast provider")

    categories = _category_map(panel, skus)
    dates = pd.DatetimeIndex(
        sorted(
            panel.frame.loc[
                (panel.frame["date"] >= start) & (panel.frame["date"] <= end), "date"
            ].unique()
        )
    )
    if len(dates) == 0:
        raise ValueError("No daily observations inside the simulation window")
    decision_dates = {date for date in dates if (date - start).days % frequency == 0}
    demand_frame = panel.frame.loc[
        (panel.frame["date"] >= start)
        & (panel.frame["date"] <= end)
        & (panel.frame["sku"].astype(str).isin(skus)),
        ["sku", "date", "units_sold"],
    ].copy()
    demand_frame["sku"] = demand_frame["sku"].astype(str)
    demand_lookup = {
        (str(row.sku), pd.Timestamp(row.date)): float(row.units_sold)
        for row in demand_frame.itertuples(index=False)
    }

    on_hand = {str(sku): float(value) for sku, value in opening.items()}
    open_orders: dict[str, list[dict[str, Any]]] = {str(sku): [] for sku in skus}
    order_counter = 0

    if bool(sim.get("include_opening_purchase_orders", False)) and not data.purchase_orders.empty:
        seed = pending_purchase_orders(data.purchase_orders, start)
        for _, row in seed.iterrows():
            sku = str(row["sku"])
            if sku in on_hand and pd.Timestamp(row["expected_arrival_date"]) > start:
                open_orders[sku].append(
                    {
                        "po_id": str(row["po_id"]),
                        "quantity": float(row["quantity"]),
                        "expected_arrival_date": pd.Timestamp(row["expected_arrival_date"]),
                    }
                )

    history_window = max(
        int(settings["demand_volatility_window_days"]),
        4 * int(max(lead.reindex(skus).fillna(1).max(), 1)) + 7,
        60,
    )
    recent_days = int(settings["overstock"]["inactive_history_days"])
    daily_rows: list[dict[str, Any]] = []
    decision_rows: list[dict[str, Any]] = []
    order_rows: list[dict[str, Any]] = []

    for day in dates:
        opening_today = {sku: float(on_hand[sku]) for sku in skus}
        received_today = {sku: 0.0 for sku in skus}
        for sku, orders in open_orders.items():
            remaining: list[dict[str, Any]] = []
            for order in orders:
                if order["expected_arrival_date"] <= day:
                    on_hand[sku] += order["quantity"]
                    received_today[sku] += order["quantity"]
                else:
                    remaining.append(order)
            open_orders[sku] = remaining

        if day in decision_dates:
            origin = day - pd.Timedelta(days=1)
            forecast = provider.forecast(origin, forecast_horizon) if provider is not None else None
            forecast_lookup = _forecast_lookup(forecast, day)
            history_lookup = _history_lookup(panel.frame, origin, history_window, skus)
            histories = {sku: values for sku, values in history_lookup.items()}
            _, category_sigma = category_volatility_fallback(
                histories,
                categories,
                min_history=int(settings["min_history_days_for_volatility"]),
            )
            overall_sigma = float(category_sigma.get("__overall__", 0.0))
            recent_start = origin - pd.Timedelta(days=recent_days)
            recent_frame = panel.frame.loc[
                (panel.frame["date"] > recent_start)
                & (panel.frame["date"] <= origin)
                & (panel.frame["sku"].astype(str).isin(skus))
            ]
            recent_units = recent_frame.groupby("sku", observed=True)["units_sold"].sum().to_dict()

            for sku in skus:
                history = history_lookup.get(str(sku), np.array([], dtype=float))
                recent_window = history[-int(settings["demand_volatility_window_days"]) :] if len(history) else history
                fallback_daily = float(recent_window.mean()) if len(recent_window) else 0.0
                values = forecast_lookup.get(str(sku), np.array([], dtype=float))
                incoming = float(sum(order["quantity"] for order in open_orders[str(sku)]))
                schedule = [
                    (order["expected_arrival_date"], float(order["quantity"]))
                    for order in open_orders[str(sku)]
                ]
                lead_days_for_sku = int(round(float(lead.get(str(sku), 1.0))))
                incoming_due = float(
                    sum(
                        order["quantity"]
                        for order in open_orders[str(sku)]
                        if pd.Timestamp(order["expected_arrival_date"])
                        <= day + pd.Timedelta(days=lead_days_for_sku)
                    )
                )
                metrics = recommendation_metrics(
                    sku=str(sku),
                    category=categories[str(sku)],
                    decision_date=day,
                    current_stock=float(on_hand[str(sku)]),
                    incoming_stock=incoming,
                    incoming_due_within_lead_time=incoming_due,
                    committed_stock=0.0,
                    committed_stock_used=False,
                    lead_time_base_days=float(lead.get(str(sku), 1.0)),
                    history=history,
                    forecast_values=values,
                    fallback_daily=fallback_daily,
                    recent_units=float(recent_units.get(str(sku), 0.0)),
                    incoming_schedule=schedule,
                    config=config,
                    service_level=level,
                    demand_multiplier=demand_multiplier,
                    forecast_source=str(getattr(provider, "name", policy)),
                )
                decision_row = {
                    "policy": policy,
                    "decision_date": day,
                    "forecast_origin_date": origin,
                    "sku": str(sku),
                    "category": categories[str(sku)],
                    **{
                        key: metrics[key]
                        for key in (
                            "current_stock",
                            "incoming_stock",
                            "inventory_position",
                            "lead_time_days",
                            "expected_daily_demand",
                            "lead_time_demand",
                            "safety_stock",
                            "reorder_point",
                            "target_stock",
                            "recommended_order_qty",
                            "days_of_cover",
                            "projected_stockout_date",
                            "stockout_risk",
                            "reorder_status",
                            "overstock_flag",
                            "excess_units",
                            "forecast_source",
                            "flags",
                        )
                    },
                }
                decision_rows.append(decision_row)

                quantity = int(metrics["recommended_order_qty"])
                if quantity > 0:
                    order_counter += 1
                    lead_days = int(metrics["lead_time_days"])
                    arrival = day + pd.Timedelta(days=lead_days)
                    order = {
                        "po_id": f"SIM-{policy}-{sku}-{order_counter:06d}",
                        "quantity": float(quantity),
                        "expected_arrival_date": arrival,
                    }
                    open_orders[str(sku)].append(order)
                    order_rows.append(
                        {
                            "policy": policy,
                            "po_id": order["po_id"],
                            "sku": str(sku),
                            "order_date": day,
                            "expected_arrival_date": arrival,
                            "quantity": quantity,
                            "lead_time_days": lead_days,
                        }
                    )

        for sku in skus:
            demand = max(0.0, float(demand_lookup.get((str(sku), day), 0.0)))
            available = max(0.0, float(on_hand[str(sku)]))
            fulfilled = min(demand, available)
            lost = max(0.0, demand - available)
            on_hand[str(sku)] = available - fulfilled
            incoming_open = float(sum(order["quantity"] for order in open_orders[str(sku)]))
            daily_rows.append(
                {
                    "policy": policy,
                    "dataset": data.mode,
                    "date": day,
                    "sku": str(sku),
                    "category": categories[str(sku)],
                    "opening_on_hand": opening_today[str(sku)],
                    "received_units": float(received_today[str(sku)]),
                    "demand_proxy_units": demand,
                    "fulfilled_units": float(fulfilled),
                    "lost_units": float(lost),
                    "closing_on_hand": float(on_hand[str(sku)]),
                    "incoming_open_units": incoming_open,
                    "inventory_position_after_sales": float(on_hand[str(sku)] + incoming_open),
                    "stockout_flag": int(lost > 1e-9),
                }
            )

    daily = pd.DataFrame(daily_rows, columns=list(SIMULATION_DAILY_COLUMNS))
    decisions = pd.DataFrame(decision_rows)
    for column in SIMULATION_DECISION_COLUMNS:
        if column not in decisions.columns:
            decisions[column] = pd.NA
    decisions = decisions.loc[:, list(SIMULATION_DECISION_COLUMNS)]
    orders = pd.DataFrame(order_rows, columns=list(SIMULATION_ORDER_COLUMNS))
    metadata = {
        "policy": policy,
        "dataset": data.mode,
        "start_date": str(start.date()),
        "end_date": str(end.date()),
        "decision_frequency_days": frequency,
        "forecast_horizon": forecast_horizon,
        "service_level": level,
        "demand_multiplier": float(demand_multiplier),
        "forecast_source": str(getattr(provider, "name", "none")),
        "forecast_fit_origins": [
            str(origin.date()) for origin in getattr(provider, "fit_origins", [])
        ],
        "skus": int(len(skus)),
        "sku_days": int(len(daily)),
        "opening_inventory_rule": "start-of-day available_stock at simulation start; same for every policy",
        "opening_purchase_orders": bool(sim.get("include_opening_purchase_orders", False)),
        "demand_definition": (
            "observed units_sold (stockout-censored sales) used as a common demand proxy; "
            "latent demand is not stored by the generator"
        ),
        "look_ahead_guard": "forecast origin is decision_date - 1 day; only prior observations are used",
    }
    LOGGER.info(
        "[inventory] simulated %s: skus=%s days=%s orders=%s",
        policy,
        len(skus),
        len(dates),
        len(orders),
    )
    return SimulationResult(policy=policy, daily=daily, decisions=decisions, orders=orders, metadata=metadata)


def _lead_series(data: InventoryData, settings: Mapping[str, Any]) -> tuple[pd.Series, pd.Series, dict[str, Any]]:
    from src.inventory.data_builder import build_lead_time_series

    return build_lead_time_series(
        data.sku_master,
        default_lead_time_days=int(settings["default_lead_time_days"]),
    )
